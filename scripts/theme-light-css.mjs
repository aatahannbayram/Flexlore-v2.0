// Generates the light-mode overrides for white utilities used on the dark design (app/theme-light.css).
// Outside a `.dark` scope, white text becomes ink and translucent white fills/lines become translucent ink.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const ROOT = new URL("..", import.meta.url).pathname; const files = [];
const walk = (d) => readdirSync(d).forEach((n) => { const p = join(d, n); statSync(p).isDirectory() ? walk(p) : n.endsWith(".tsx") && files.push(p); });
walk(join(ROOT, "components")); walk(join(ROOT, "app"));
const re = /\b((?:hover:|group-hover:|lg:|md:|sm:)?)(text|bg|ring|border|divide|decoration)-white(?:\/(\[[.0-9]+\]|[0-9]+))?(?![\w\/-])/g;
const seen = new Map();
for (const f of files) for (const m of readFileSync(f, "utf8").matchAll(re)) seen.set(m[0], m);
const esc = (s) => s.replace(/([:\/\[\].])/g, "\\$1");
const alpha = (a) => (a == null ? 1 : a.startsWith("[") ? parseFloat(a.slice(1, -1)) : parseInt(a, 10) / 100);
const out = ["/* Generated by scripts/theme-light-css.mjs. Do not edit by hand. */"];
for (const [cls, m] of [...seen].sort()) {
  const [, pre, kind, raw] = m; const a = alpha(raw);
  let decl;
  if (kind === "text") decl = `color: rgb(22 22 22 / ${a >= 0.99 ? 1 : Math.max(a, 0.66)})`;
  else if (kind === "bg") { if (a >= 0.8) continue; decl = `background-color: rgb(22 22 22 / ${Math.min(+(a * 0.85).toFixed(3), 0.3)})`; }
  else if (kind === "decoration") decl = `text-decoration-color: rgb(22 22 22 / ${a})`;
  else if (kind === "ring") decl = `--tw-ring-color: rgb(22 22 22 / ${Math.min(Math.max(a, 0.08), 0.3)})`;
  else decl = `border-color: rgb(22 22 22 / ${Math.min(Math.max(a, 0.08), 0.3)})`;
  const base = `.${esc(cls)}`;
  const sel = pre === "hover:" ? `${base}:hover` : pre === "group-hover:" ? `.group:hover ${base}` : base;
  const rule = `:root[data-theme="light"] ${sel}:not(.dark, .dark *) { ${decl}; }`;
  out.push(pre === "lg:" ? `@media (min-width: 1024px) { ${rule} }` : pre === "md:" ? `@media (min-width: 768px) { ${rule} }` : pre === "sm:" ? `@media (min-width: 640px) { ${rule} }` : rule);
}
writeFileSync(join(ROOT, "app/theme-light.css"), out.join("\n") + "\n");
console.log(`theme-light: ${out.length - 1} rules`);

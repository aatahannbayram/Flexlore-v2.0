// Builds components/ui/icons.tsx from @phosphor-icons/core SVGs: only the icons the site imports, only the
// "regular" and "fill" weights. Phosphor stays the single icon set; we just stop shipping six weights per icon.
// Usage: node scripts/build-icons.mjs   (scans components/ for `from "<...>/ui/icons"` and Phosphor imports)
import { readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, relative, dirname } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const ASSETS = join(ROOT, "node_modules/@phosphor-icons/core/assets");
const OUT = join(ROOT, "components/ui/icons.tsx");
const IMPORT = /import\s*\{([^{}]*?)\}\s*from\s*"((?:@phosphor-icons\/react\/dist\/ssr)|(?:[./]+(?:ui\/)?icons))"/g;

const files = [];
const walk = (d) => readdirSync(d).forEach((n) => { const p = join(d, n); statSync(p).isDirectory() ? walk(p) : /\.tsx?$/.test(n) && p !== OUT && files.push(p); });
walk(join(ROOT, "components"));

const names = new Set();
for (const f of files) {
  let s = readFileSync(f, "utf8"); let changed = false;
  s = s.replace(IMPORT, (all, list, from) => {
    if (from !== "@phosphor-icons/react/dist/ssr" && !/ui\/icons$|^\.\/icons$/.test(from)) return all;
    list.split(",").map((x) => x.trim()).filter(Boolean).forEach((n) => names.add(n));
    let rel = relative(dirname(f), join(ROOT, "components/ui/icons")); if (!rel.startsWith(".")) rel = "./" + rel;
    changed = true; return `import {${list}} from "${rel}"`;
  });
  if (changed) writeFileSync(f, s);
}

const kebab = (n) => n.replace(/([a-z0-9])([A-Z])/g, "$1-$2").replace(/([A-Z])([A-Z][a-z])/g, "$1-$2").toLowerCase();
const inner = (w, n) => readFileSync(join(ASSETS, w, `${kebab(n)}${w === "regular" ? "" : "-" + w}.svg`), "utf8").replace(/^<svg[^>]*>|<\/svg>\s*$/g, "");
// One module per icon (components/ui/icons/<Name>.tsx) behind a re-export barrel, so each chunk ships only its own icons.
// pointer-events: none keeps the button (not the inner paths, which React may rewrite on re-render) as the click target;
// without it a re-render between mousedown and mouseup swallowed the click (seen on the mobile menu button).
import("node:fs").then(({ mkdirSync, rmSync }) => {
  const DIR = join(ROOT, "components/ui/icons");
  rmSync(DIR, { recursive: true, force: true }); mkdirSync(DIR, { recursive: true });
  writeFileSync(join(DIR, "_mk.tsx"), [
    "// GENERATED by scripts/build-icons.mjs. Do not edit by hand.",
    "export type IconProps = { size?: number | string; weight?: \"regular\" | \"fill\"; className?: string; style?: React.CSSProperties; \"aria-hidden\"?: boolean | \"true\" | \"false\" };",
    "export const mk = (r: string, f: string) => function Icon({ size = 24, weight = \"regular\", className, style, ...rest }: IconProps) {",
    "  return <svg xmlns=\"http://www.w3.org/2000/svg\" viewBox=\"0 0 256 256\" width={size} height={size} fill=\"currentColor\" className={className} style={{ pointerEvents: \"none\", ...style }} aria-hidden={rest[\"aria-hidden\"] ?? true} focusable=\"false\" dangerouslySetInnerHTML={{ __html: weight === \"fill\" ? f : r }} />;",
    "};", ""].join("\n"));
  const barrel = ["// GENERATED by scripts/build-icons.mjs from @phosphor-icons/core (regular + fill only). Do not edit by hand."];
  for (const n of [...names].sort()) {
    writeFileSync(join(DIR, `${n}.tsx`), `import { mk } from "./_mk";\nexport const ${n} = /*#__PURE__*/ mk(${JSON.stringify(inner("regular", n))}, ${JSON.stringify(inner("fill", n))});\n`);
    barrel.push(`export { ${n} } from "./icons/${n}";`);
  }
  writeFileSync(OUT, barrel.join("\n") + "\n");
  console.log(`build-icons: ${names.size} icons -> components/ui/icons/*.tsx (+ barrel components/ui/icons.tsx)`);
});
